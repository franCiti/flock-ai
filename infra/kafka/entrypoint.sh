#!/usr/bin/env bash
# Starts the Kafka broker with the flock-ai configuration (plan section 7.2).
#
# Runs as root only to read the private key (certs-init writes it with mode 600, owned by root),
# writes the configuration for the unprivileged "appuser" and then drops privileges.
set -euo pipefail

# shellcheck source=infra/kafka/tls.sh
. /etc/flock/kafka/tls.sh

readonly RUNTIME_DIR=/tmp/flock
readonly CONFIG=$RUNTIME_DIR/server.properties
readonly HEALTHCHECK_CONFIG=$RUNTIME_DIR/healthcheck.properties

install -d -o appuser -g appuser -m 700 "$RUNTIME_DIR"
umask 077
{
  cat /etc/flock/kafka/server.properties
  echo
  echo "# --- TLS material (generated by entrypoint.sh) ---"
  pem_property ssl.keystore.certificate.chain /certs/kafka.crt
  pem_property ssl.keystore.key /certs/kafka.key
  pem_property ssl.truststore.certificates /certs/ca.crt
} >"$CONFIG"

# The health check connects as a client with the broker's own certificate.
client_properties /certs kafka >"$HEALTHCHECK_CONFIG"
chown appuser:appuser "$CONFIG" "$HEALTHCHECK_CONFIG"

# BusyBox su replaces itself with the shell, which execs Kafka: no intermediate process is left
# and Kafka receives the stop signals directly. -p keeps the environment (PATH, JAVA_HOME...).
as_appuser() {
  su -p -s /bin/bash appuser -c "$1"
}

as_appuser "/opt/kafka/bin/kafka-storage.sh format --config $CONFIG --cluster-id $CLUSTER_ID \
  --ignore-formatted"

exec su -p -s /bin/bash appuser -c "exec /opt/kafka/bin/kafka-server-start.sh $CONFIG"
