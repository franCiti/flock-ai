package ar.com.flockit.flockai.core.common;

import static org.assertj.core.api.Assertions.assertThat;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import ar.com.flockit.flockai.core.support.IntegrationTest;
import java.nio.file.Files;
import java.nio.file.Path;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.test.web.servlet.assertj.MockMvcTester;

/** The documentation under /docs is visible without a session (plan 2.7, 6.3). */
@IntegrationTest
@AutoConfigureMockMvc
class DocsTest {

    @Autowired
    private MockMvcTester mvc;

    @Test
    void theIndexLinksBothDocuments() {
        assertThat(mvc.get().uri("/docs")).hasStatus3xxRedirection().hasRedirectedUrl("/docs/");
        assertThat(mvc.get().uri("/docs/")).hasStatusOk().hasForwardedUrl("/docs/index.html");
        assertThat(mvc.get().uri("/docs/index.html"))
                .hasStatusOk()
                .bodyText()
                .contains("swagger-ui/index.html", "asyncapi/");
    }

    @Test
    void swaggerUiAndTheOpenApiSpecification() {
        assertThat(mvc.get().uri("/docs/openapi")).hasStatusOk();
        assertThat(mvc.get().uri("/docs/swagger-ui/index.html")).hasStatusOk();
    }

    @Test
    void theAsyncApiDocumentation() {
        // Generated by contracts/build-docs.sh (scripts/check.sh and the image run it first).
        Path docs = Path.of(System.getProperty("contracts.dir"), "docs", "index.html");
        assumeTrue(Files.exists(docs), "contracts/docs not generated: run contracts/build-docs.sh");

        assertThat(mvc.get().uri("/docs/asyncapi")).hasStatus3xxRedirection().hasRedirectedUrl("/docs/asyncapi/");
        assertThat(mvc.get().uri("/docs/asyncapi/")).hasStatusOk().hasForwardedUrl("/docs/asyncapi/index.html");
        assertThat(mvc.get().uri("/docs/asyncapi/index.html"))
                .hasStatusOk()
                .bodyText()
                .contains("AgentRequest", "js/asyncapi-ui.min.js");
        assertThat(mvc.get().uri("/docs/asyncapi/js/asyncapi-ui.min.js")).hasStatusOk();
        assertThat(mvc.get().uri("/docs/asyncapi/css/asyncapi.min.css")).hasStatusOk();
    }
}
